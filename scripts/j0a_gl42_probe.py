#!/usr/bin/env python3
"""j0a_gl42_probe.py -- J0a' at p = 2, k = 3, c = 16 (general-k-note.md §1).

GL(4, 2) (order 20160) acts on the 16 vectors of F_2^4.  Subgroups are generated by a
conjugacy-class representative and a second element (all of them, or a random sample),
with closures abandoned past CAP elements (Oliver-admissible groups here are small).
Each is tested for Oliver-admissibility with chain prime 2 (O_2(H), then the q'-generated
subgroup cyclic modulo it) and for semilinearity (inside a Singer normaliser, a conjugate
of GammaL(1, 16)); the least orbit of F_2^4 x| H on 3-sets is compared with
AGammaL(1, 16)'s 80.

    python3 j0a_gl42_probe.py [samples_per_rep] [--irreducible]

With --irreducible only primitive blocks (H irreducible) are scored, which is the
framework's setting (enumeration-proof.md B1); reducible H give imprimitive blocks, i.e.
fused classes, scored elsewhere.
"""
import sys, random
from itertools import combinations, product
from math import gcd
CAP = 1000
vecs = list(product(range(2), repeat=4)); vi = {v: i for i, v in enumerate(vecs)}
def matperm(M):
    return tuple(vi[tuple(sum(M[r][k]*v[k] for k in range(4)) % 2 for r in range(4))] for v in vecs)
mats = [M for M in product(product(range(2), repeat=4), repeat=4)]
G = []
for M in mats:
    P = matperm(M)
    if len(set(P)) == 16: G.append(P)
I = tuple(range(16))
def mul(a, b): return tuple(a[i] for i in b)      # a after b
def order(a):
    k, x = 1, a
    while x != I: x = mul(a, x); k += 1
    return k
def close(gens, cap=CAP):
    S = {I}; fr = [I]
    while fr:
        nf = []
        for x in fr:
            for g in gens:
                y = mul(g, x)
                if y not in S:
                    S.add(y); nf.append(y)
                    if len(S) > cap: return None
        fr = nf
    return frozenset(S)
inv = {}
for g in G:
    h = [0]*16
    for i, j in enumerate(g): h[j] = i
    inv[g] = tuple(h)
seen, reps = set(), []
for a in G:
    if a in seen: continue
    reps.append(a)
    for g in G: seen.add(mul(mul(g, a), inv[g]))
singers = {close([a], 10**6) for a in G if order(a) == 15}
def ppow(n, p):
    while n % p == 0: n //= p
    return n == 1
def admissible(H):
    # O_2(H) = core of a Sylow 2-subgroup (built greedily)
    S = frozenset([I])
    for x in H:
        if ppow(order(x), 2) and x not in S:
            T = close(list(S) + [x], 10**6)
            if ppow(len(T), 2): S = T
    P0 = S
    for g in H:
        P0 = frozenset(y for y in P0 if mul(mul(inv[g], y), g) in S)
    for q in (2, 3, 5, 7):
        K = close([h for h in H if gcd(order(h), q) == 1], 10**6)
        KP = close(list(K | P0), 10**6)
        if any(len(close([x] + list(P0), 10**6)) == len(KP) for x in KP):
            return True
    return False
pts3 = [s for s in combinations(range(1, 16), 2)]
def min3(H):
    best = 1
    for x, y in pts3:
        S = {0, x, y}; st = 0
        for A in H:
            im = [A[s] for s in (0, x, y)]
            for w in (0, x, y):
                if {u ^ w for u in im} == S: st += 1   # index arithmetic = vector addition? no
        best = max(best, st)
    return 16 * len(H) // best
# vector addition on indices: vecs ordered by product, so index = binary of the tuple -> XOR works
assert all(vi[tuple((a + b) % 2 for a, b in zip(vecs[i], vecs[j]))] == i ^ j for i in range(16) for j in range(16))
nums = [x for x in sys.argv[1:] if x.isdigit()]
samples = int(nums[0]) if nums else None
random.seed(1)
subs = {}
for a in reps:
    pool = G if samples is None else random.sample(G, samples)
    for b in pool:
        H = close([a, b])
        if H is not None and H not in subs: subs[H] = (a, b)
def irreducible(H):
    # framework blocks are primitive (enumeration-proof.md B1): H irreducible.
    # index arithmetic is XOR, so the span of a set is its closure under XOR
    for v in range(1, 16):
        span = {0}
        for w in {A[v] for A in H}:
            span |= {u ^ w for u in span}
        if len(span) < 16: return False
    return True
best = {}
for H in subs:
    if not admissible(H): continue
    if '--irreducible' in sys.argv and not irreducible(H): continue
    gens = subs[H]
    semi = any(all(mul(mul(g, x), inv[g]) in S for g in gens for x in S) for S in singers)
    m = min3(H)
    if semi not in best or m > best[semi][0]: best[semi] = (m, len(H))
print(f"c = 16: {len(subs)} subgroups (cap {CAP}); best semilinear {best.get(True)}, "
      f"best non-semilinear {best.get(False)}  (min3, |H|); AGammaL(1,16): 80")
