#!/usr/bin/env python3
"""j0a_a3_probe.py -- J0a' at a = 3, k = 3 (general-k-note.md §1).

(1) c = 8: every subgroup of GL(3, 2) generated by two elements, as in
    j0a_gl2_search.py.
(2) c = 343: the families the note's component argument has to handle, built
    directly in GL(3, 7): the Sylow 3-subgroup C3 wr C3 (order 81, larger than the
    3-part 27 of GammaL(1, 343)); the extraspecial 3^{1+2} with and without scalars;
    the monomial C6 wr C3 and its 2- and 3-parts; GammaL(1, 49) + GL(1, 7)-parts
    (reducible).  Each is tested for Oliver-admissibility (chain prime p) and its least
    3-orbit computed, against AGammaL(1, 343)'s 39102.
"""
import sys
from itertools import combinations, product
from math import gcd

def mk(p, n):
    def mul(A, B):
        return tuple(tuple(sum(A[i][k]*B[k][j] for k in range(n)) % p for j in range(n)) for i in range(n))
    I = tuple(tuple(int(i == j) for j in range(n)) for i in range(n))
    def order(A):
        k, X = 1, A
        while X != I:
            X = mul(X, A); k += 1
        return k
    def close(gens):
        S = {I}; fr = [I]
        while fr:
            nf = []
            for X in fr:
                for g in gens:
                    Y = mul(X, g)
                    if Y not in S: S.add(Y); nf.append(Y)
            fr = nf
        return frozenset(S)
    return mul, I, order, close

def primes(n):
    out, d = set(), 2
    while d*d <= n:
        while n % d == 0: out.add(d); n //= d
        d += 1
    if n > 1: out.add(n)
    return out

def admissible(H, p, mul, order, close, I, qcands):
    ordr = {h: order(h) for h in H}
    def ppow(n):
        while n % p == 0: n //= p
        return n == 1
    inv = {}
    for h in H:
        X = I
        for _ in range(ordr[h] - 1): X = mul(X, h)
        inv[h] = X
    pel = [h for h in H if ppow(ordr[h])]
    P0 = close(pel)
    if not (ppow(len(P0)) and all(mul(mul(g, x), inv[g]) in P0 for g in H for x in P0)):
        P0 = frozenset([I])
    out = []
    for q in qcands:
        K = close([h for h in H if gcd(ordr[h], q) == 1])
        KP = close(list(K | P0))
        if any(len(close([x] + list(P0))) == len(KP) for x in KP):
            out.append(q)
    return out

def min3(H, p, n):
    V = list(product(range(p), repeat=n)); z = V[0]; nz = V[1:]
    def act(A, v): return tuple(sum(A[i][j]*v[j] for j in range(n)) % p for i in range(n))
    Hl = list(H); best = 1
    for x, y in combinations(nz, 2):
        S = (z, x, y); Sset = set(S); st = 0
        imgs = [[act(A, s) for s in S] for A in Hl]
        for im in imgs:
            for w in S:
                if {tuple((a + b) % p for a, b in zip(u, w)) for u in im} == Sset:
                    st += 1
        best = max(best, st)
    return p**n * len(H) // best

def part1():
    p, n = 2, 3
    mul, I, order, close = mk(p, n)
    def det(A):
        (a, b, c), (d, e, f), (g, h, i) = A
        return (a*(e*i - f*h) - b*(d*i - f*g) + c*(d*h - e*g)) % 2
    rows = list(product(range(2), repeat=3))
    G = [A for A in product(rows, rows, rows) if det(A)]
    G = [tuple(map(tuple, A)) for A in G]
    subs = {close([A, B]) for A in G for B in G}
    singers = {close([A]) for A in G if order(A) == 7}
    inv = {A: next(B for B in G if mul(A, B) == I) for A in G}
    norms = [frozenset(g for g in G if all(mul(mul(g, s), inv[g]) in S for s in S)) for S in singers]
    res = {}
    for H in subs:
        qs = admissible(H, p, mul, order, close, I, sorted(primes(168) | {p}))
        if not qs: continue
        semi = any(H <= N for N in norms)
        m = min3(H, p, n)
        for q in qs:
            k = (q, semi)
            if k not in res or m > res[k][0]: res[k] = (m, len(H))
    print(f"c = 8: {len(subs)} subgroups of GL(3,2)")
    for q in sorted({k[0] for k in res}):
        s, ns = res.get((q, True)), res.get((q, False))
        flag = "  <-- non-semilinear WINS" if ns and (not s or ns[0] > s[0]) else ""
        print(f"  q = {q}: best semilinear {s}, best non-semilinear {ns}{flag}")

def part2():
    p, n = 7, 3
    mul, I, order, close = mk(p, n)
    def D(a, b, c): return ((a, 0, 0), (0, b, 0), (0, 0, c))
    perm = ((0, 0, 1), (1, 0, 0), (0, 1, 0))
    w = 2   # order 3 mod 7
    fams = {
        "C3 wr C3 (Sylow-3, |H| = 81)": [D(w, 1, 1), perm],
        "3^{1+2}": [D(1, w, w*w % 7), perm],
        "3^{1+2} . scalars C6": [D(1, w, w*w % 7), perm, D(3, 3, 3)],
        "C6 wr C3": [D(3, 1, 1), perm],
        "C2 wr C3": [D(6, 1, 1), perm],
    }
    # GammaL(1,49) on F_49 = F_7[i], i^2 = 3 (non-residue), plus a GL(1,7) part
    def emb(M2, s): return ((M2[0][0], M2[0][1], 0), (M2[1][0], M2[1][1], 0), (0, 0, s))
    # multiplication by a generator g = a + b i of F_49^*: matrix [[a, 3b], [b, a]]
    mul2, I2, order2, close2 = mk(7, 2)
    gen49 = next(((a, 3*b % 7), (b, a)) for a in range(7) for b in range(1, 7)
                 if order2(((a, 3*b % 7), (b, a))) == 48)
    frob = ((1, 0), (0, 6))
    fams["GammaL(1,49) x C2 (reducible, |H| = 192)"] = [emb(gen49, 1), emb(frob, 1), D(1, 1, 6)]
    fams["GammaL(1,49) x C6 (reducible)"] = [emb(gen49, 1), emb(frob, 1), D(1, 1, 3)]
    print("c = 343, against AGammaL(1, 343): least 3-orbit 39102")
    for name, gens in fams.items():
        H = close(gens)
        qs = admissible(H, p, mul, order, close, I, [2, 3, 7, 19])
        m = min3(H, p, n) if qs else None
        print(f"  {name}: |H| = {len(H)}, admissible for q in {qs}, least 3-orbit {m}")

if __name__ == "__main__":
    part1()
    if '--quick' not in sys.argv:
        part2()
