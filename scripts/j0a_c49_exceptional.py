#!/usr/bin/env python3
"""J0a' at k = 3, the Huppert-exceptional block sizes c = p^2, p in {5, 7, 11, 23} (general-k-note.md §1).

If +-H is solvable, transitive on the nonzero vectors and not semilinear, Huppert's theorem puts
it in N(Q8) for a Q8 <= GL(2, p).  Since H <= HQ8 <= N(Q8), min3(H) <= min3(HQ8), so it suffices
to enumerate the subgroups of N_{GL(2,p)}(Q8) containing Q8 whose +-closure is transitive and
record Oliver-admissibility and compare their least 3-orbit with AGammaL(1, p^2)'s.  (All Q8's in GL(2, p) are conjugate.)

    python3 j0a_c49_exceptional.py 5 7 11 23        # subgroups containing Q8
    python3 j0a_c49_exceptional.py 5 7 --all        # every subgroup of N(Q8)
"""
import sys
from itertools import combinations
def run(p):
    def mul(A, B):
        a, b, c, d = A; e, f, g, h = B
        return ((a*e+b*g) % p, (a*f+b*h) % p, (c*e+d*g) % p, (c*f+d*h) % p)
    I = (1, 0, 0, 1)
    G = [(a, b, c, d) for a in range(p) for b in range(p) for c in range(p) for d in range(p) if (a*d-b*c) % p]
    def close(gens):
        S = {I}; fr = [I]
        while fr:
            nf = []
            for X in fr:
                for g in gens:
                    Y = mul(X, g)
                    if Y not in S: S.add(Y); nf.append(Y)
            fr = nf
        return frozenset(S)
    def inv1(A):
        a, b, c, d = A; di = pow((a*d-b*c) % p, p-2, p)
        return (d*di % p, (-b)*di % p, (-c)*di % p, a*di % p)
    inv = {A: inv1(A) for A in G}
    def order(A):
        k, X = 1, A
        while X != I: X = mul(X, A); k += 1
        return k
    # a Q8: generated by two elements of order 4 with square -1, anticommuting
    m1 = (p - 1, 0, 0, p - 1)
    fours = [A for A in G if order(A) == 4 and mul(A, A) == m1]
    Q = None
    for A in fours:
        for B in fours:
            if mul(A, B) == mul(mul(B, A), m1):
                Q = close([A, B]); break
        if Q: break
    N = [g for g in G if all(mul(mul(g, x), inv[g]) in Q for x in Q)]
    subs = {close(list(Q) + [a, b]) for a in N for b in N}
    if '--all' in sys.argv:
        # every subgroup of N(Q8), by closing under adjoining one element at a time
        subs = {frozenset([I])}
        frontier = list(subs)
        while frontier:
            nf = []
            for H in frontier:
                for g in N:
                    if g not in H:
                        K = close(list(H) + [g])
                        if K not in subs:
                            subs.add(K); nf.append(K)
            frontier = nf
    V = [(x, y) for x in range(p) for y in range(p)]
    nz = V[1:]
    def act(A, v): return ((A[0]*v[0]+A[1]*v[1]) % p, (A[2]*v[0]+A[3]*v[1]) % p)
    def min3(H):
        best = 1
        for x, y in combinations(nz, 2):
            S = {(0, 0), x, y}; st = 0
            for A in H:
                im = [act(A, s) for s in S]
                for w in S:
                    if {((u[0]+w[0]) % p, (u[1]+w[1]) % p) for u in im} == S: st += 1
            best = max(best, st)
        return p * p * len(H) // best
    out = []
    for H in subs:
        Hpm = close(list(H) + [m1])
        orb = {act(A, (1, 0)) for A in Hpm}
        if len(orb) == p*p - 1:
            # Oliver-admissible (O_p(H) = 1 here, H being irreducible): for some prime q
            # the subgroup generated by the q'-elements is cyclic
            from math import gcd
            adm = []
            for q in (2, 3, 5, 7, 11, 23):
                Kq = close([h for h in H if gcd(order(h), q) == 1])
                if any(len(close([x])) == len(Kq) for x in Kq):
                    adm.append(q)
            out.append((min3(H), len(H), tuple(adm)))
    print(f"|N(Q8)| = {len(N)}, subgroups enumerated: {len(subs)}, +-transitive: {len(out)}")
    ref = p*p*(p*p-1)//(3 if (p*p-1) % 3 == 0 else 2)
    print(f"p = {p}: least 3-orbits (min3, |H|, admissible q):", sorted(set(out)), f" vs AGammaL(1,{p*p}): {ref}")

for p in [int(x) for x in sys.argv[1:] if x.isdigit()] or [5, 7]:
    run(p)
