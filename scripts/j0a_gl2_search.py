#!/usr/bin/env python3
"""j0a_gl2_search.py -- a probe of J0a' (general-k-note.md §1) at k = 3 on blocks of size p^2.

For every subgroup H of GL(2, p) generated by two elements (optionally with the
scalars adjoined), test:
  * Oliver-admissibility of V x| H: with P0 = O_p(H) and some prime q, the subgroup
    K generated by the q'-elements has K.P0/P0 cyclic (then C = K.P0 is the cyclic
    layer and H/C a q-group);
  * semilinearity: H inside the normaliser of some Singer cycle (a conjugate of
    GammaL(1, p^2));
  * the least orbit of V x| H on 3-subsets of F_p^2 (every orbit meets a set
    containing 0, and a stabilising element maps 0 into the set).
Reports, per top prime q, the best least 3-orbit over admissible non-semilinear H
and over admissible semilinear H.  J0a' predicts the former never exceeds the latter.
Not exhaustive over subgroups that need three generators.

    python3 j0a_gl2_search.py 3 5 7
"""
import sys
from itertools import combinations
from math import gcd

def run(p):
    def mul(A, B):
        a, b, c, d = A; e, f, g, h = B
        return ((a*e+b*g) % p, (a*f+b*h) % p, (c*e+d*g) % p, (c*f+d*h) % p)
    I = (1, 0, 0, 1)
    G = [(a, b, c, d) for a in range(p) for b in range(p) for c in range(p) for d in range(p)
         if (a*d - b*c) % p]
    def order(A):
        k, X = 1, A
        while X != I:
            X = mul(X, A); k += 1
        return k
    ordr = {A: order(A) for A in G}
    inv = {}
    for A in G:
        X = A
        for _ in range(ordr[A] - 2):
            X = mul(X, A)
        inv[A] = X if ordr[A] > 1 else I
    def close(gens):
        S = {I}; frontier = [I]
        while frontier:
            nf = []
            for X in frontier:
                for g in gens:
                    Y = mul(X, g)
                    if Y not in S:
                        S.add(Y); nf.append(Y)
            frontier = nf
        return frozenset(S)
    # conjugacy class representatives for the first generator
    seen, reps = set(), []
    for A in G:
        if A in seen: continue
        reps.append(A)
        for g in G:
            seen.add(mul(mul(g, A), inv[g]))
    scal = [(s, 0, 0, s) for s in range(1, p)]
    zgen = next(s for s in scal if ordr[s] == p - 1)
    subs = set()
    for A in reps:
        for B in G:
            H = close([A, B]); subs.add(H)
            subs.add(close([A, B, zgen]))
    # Singer normalisers
    singers = set()
    for A in G:
        if ordr[A] == p*p - 1:
            singers.add(close([A]))
    norms = []
    for S in singers:
        N = frozenset(g for g in G if all(mul(mul(g, s), inv[g]) in S for s in S))
        norms.append(N)
    def primes(n):
        out, d = set(), 2
        while d*d <= n:
            while n % d == 0: out.add(d); n //= d
            d += 1
        if n > 1: out.add(n)
        return out
    def is_pgroup_order(n, r):
        while n % r == 0: n //= r
        return n == 1
    def admissible(H):
        n = len(H)
        # O_p(H): intersection of Sylow p's = the set of p-elements if it is a normal subgroup; brute
        pel = [h for h in H if is_pgroup_order(ordr[h], p)]
        P0 = close(pel) if pel else frozenset([I])
        while not is_pgroup_order(len(P0), p):   # the p-elements may not form a group: shrink
            P0 = frozenset(x for x in P0 if all(mul(mul(g, x), inv[g]) in P0 for g in H))
            P0 = close(list(P0)) if P0 else frozenset([I])
            if not is_pgroup_order(len(P0), p):
                P0 = frozenset([I]); break
        if not all(mul(mul(g, x), inv[g]) in P0 for g in H for x in P0):
            P0 = frozenset([I])
        qs = []
        for q in primes(len(G)) | {p}:
            K = close([h for h in H if gcd(ordr[h], q) == 1])
            KP = close(list(K | P0))
            # KP/P0 cyclic: some element generates KP modulo P0
            m = len(KP) // len(P0)
            ok = any(len(close([x] + list(P0))) == len(KP) for x in KP)
            if ok:
                qs.append(q)
        return qs
    V = [(x, y) for x in range(p) for y in range(p)]
    def act(A, v): return ((A[0]*v[0]+A[1]*v[1]) % p, (A[2]*v[0]+A[3]*v[1]) % p)
    nz = [v for v in V if v != (0, 0)]
    def min3(H):
        best = 0
        for x, y in combinations(nz, 2):
            S = {(0, 0), x, y}; st = 0
            for A in H:
                for w in S:   # g = A then translate by w: 0 -> w
                    img = {((a+w[0]) % p, (b+w[1]) % p) for (a, b) in (act(A, s) for s in S)}
                    if img == S: st += 1
            best = max(best, st)
        return p*p*len(H) // best
    res = {}
    for H in subs:
        qs = admissible(H)
        if not qs: continue
        semi = any(H <= N for N in norms)
        m = min3(H)
        for q in qs:
            key = (q, semi)
            if key not in res or m > res[key][0]:
                res[key] = (m, len(H))
    print(f"p = {p}, c = {p*p}: {len(subs)} subgroups probed")
    for q in sorted({k[0] for k in res}):
        s = res.get((q, True)); n = res.get((q, False))
        flag = "  <-- non-semilinear WINS" if n and (not s or n[0] > s[0]) else ""
        print(f"  q = {q}: best semilinear {s}, best non-semilinear {n}  (min3, |H|){flag}")

for p in map(int, sys.argv[1:] or ["3", "5"]):
    run(p)
